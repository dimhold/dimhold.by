/* Подписи ручек демонстраций на английском и белорусском.
 *
 * Описания демонстраций в demos.ts пишутся по-русски, и Demo.astro строит по ним панель.
 * Для других языков подпись ищется здесь по русскому тексту: так в demos.ts остаётся
 * одно описание на экспонат, а не три. Подпись, которой здесь нет, выводится
 * по-русски — это заметно и чинится добавлением строки.
 */
import type { IllLang } from './labels';

export const DEMO_TEXT: Record<'en' | 'be', Record<string, string>> = {
  en: {},
  be: {},
};

/** Подпись ручки на языке страницы. */
export const dt = (lang: IllLang, s: string): string => (lang === 'ru' ? s : (DEMO_TEXT[lang][s] ?? s));
